function getFileSizeMb(fileName: string): string | null {
  try {
    const filePath = path.join(process.cwd(), 'public', fileName);
    const { size } = fs.statSync(filePath);
    return (size / (1024 * 1024)).toFixed(1);
  } catch {
    return null;
  }
}

